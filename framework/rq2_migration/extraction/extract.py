# 历史流水线遗留的内部标记，clean trunk 不外泄
_DROP_KEYS = {"linked_in_v311", "linked_in_v39", "linker_hpp", "linker_cpp", "merged_from_v2"}


def _safe_filename(s: str, max_len: int = 100) -> str:
    """非法字符 → 下划线；超长截断 + 8 位 hash（Windows 路径 < 260）。"""
    base = re.sub(r"[^\w]+", "_", s).strip("_") or "x"
    if len(base) > max_len:
        import hashlib
        h = hashlib.md5(base.encode("utf-8")).hexdigest()[:8]
        base = base[: max_len - 9] + "_" + h
    return base


def _clean_record(r: Dict) -> Dict:
    """去掉 `_`-前缀临时键与历史内部标记。"""
    return {k: v for k, v in r.items() if not k.startswith("_") and k not in _DROP_KEYS}


def _resolve_source_cpp(file_path: str) -> Path | None:
    """把 record.file_path 解析成源码树里的真实文件（供 registrations.cpp 取原文）。"""
    if not file_path:
        return None
    key = file_path.replace("\\", "/")
    cand = config.SOURCE_ROOT / key
    if cand.exists():
        return cand
    root = config.VK_MODULES_ROOT
    cand = root / key
    if cand.exists():
        return cand
    matches = list(root.rglob(Path(key).stem + ".*"))
    matches = [m for m in matches if m.suffix in (".cpp", ".hpp")]
    if matches:
        return matches[0]
    return None


def _render_appendix(regs: List[Dict], cpp_stem: str) -> str:
    """复刻 append_registrations_to_cpp.render_appendix 的注释块格式。"""
    L: List[str] = ["", "", "// " + "=" * 78,
                    f"// === Extracted Test Cases ({len(regs)} records) ===",
                    f"// Module cpp_stem: {cpp_stem}",
                    "// Generated by extract.py", "// " + "=" * 78, ""]
    cur = -1
    for r in sorted(regs, key=lambda x: (x.get("line") or 0, x.get("record_name") or "")):
        ln = r.get("line", 0) or 0
        if ln != cur:
            L += ["", f"// --- line {ln} ---"]
            cur = ln
        name, qn = r.get("record_name", "?"), r.get("qualified_name", "")
        pfx = f"// [{r.get('kind','?')}] {name}"
        if qn and qn != name:
            pfx += f"  ({qn})"
        pfx += f"  class={r.get('registration_class','?')}"
        L.append(pfx)
        for cl in r.get("call", "").strip().split("\n"):
            L.append("//     " + cl if cl.strip() else cl)
    L += ["", "// " + "=" * 78, "// === End of Extracted Test Cases ===", "// " + "=" * 78]
    return "\n".join(L)


def _category_of(cpp: Path, modules_root: Path, out_root: Path) -> str:
    """叶子的 sub_module 段：取相对 modules_root 的首级目录名；
    根级文件(无子目录)退化为数据集名(out_root.name)，与参考约定一致。"""
    parts = cpp.relative_to(modules_root).parts
    return parts[0] if len(parts) > 1 else out_root.name


def _assign_ids(class_recs: List[Dict], func_recs: List[Dict],
                category: str, cpp_stem: str) -> None:
    """v3.31 结构编号（就地写入）：
    - class_id = <category>_<stem>__<type>_<n>，type=class/function，n 按数组序从 0 计。
    - child 记录另补 class_type='child'、trace={sub_module,file_stem}；decl_kind 由提取器原生保留。
    - function 记录只补 class_id（与参考 schema 对齐：其 class_type/decl_kind/trace 为空）。
    """
    for n, r in enumerate(class_recs):
        r["class_id"] = f"{category}_{cpp_stem}__class_{n}"
        r["class_type"] = "child"
        r["trace"] = {"sub_module": category, "file_stem": cpp_stem}
    for n, r in enumerate(func_recs):
        r["class_id"] = f"{category}_{cpp_stem}__function_{n}"


def _write_module(records: List[Dict], category: str, cpp_stem: str, out_root: Path) -> None:
    """把一个 cpp 的 records 落盘为一个数据集叶子目录。"""
    module_dir = out_root / category / cpp_stem
    module_dir.mkdir(parents=True, exist_ok=True)

    class_recs = [r for r in records if r.get("test_type") == "class_based"]
    func_recs = [r for r in records if r.get("test_type") == "function_based"]
    _assign_ids(class_recs, func_recs, category, cpp_stem)

    if class_recs:
        (module_dir / "child_class.json").write_text(
            json.dumps([_clean_record(r) for r in class_recs], ensure_ascii=False, indent=2),
            encoding="utf-8")
    if func_recs:
        (module_dir / "function_tests.json").write_text(
            json.dumps([_clean_record(r) for r in func_recs], ensure_ascii=False, indent=2),
            encoding="utf-8")

    # case_sources/ ：每条 record 的自包含 cpp（内容 = record.code）
    self_dir = module_dir / "case_sources"
    self_dir.mkdir(exist_ok=True)
    for r in class_recs + func_recs:
        ns = (r.get("namespace", "").split("::")[-1]) if r.get("namespace") else ""
        stem = f"{cpp_stem}__{ns}_{r['name']}" if ns else f"{cpp_stem}__{r['name']}"
        (self_dir / f"{_safe_filename(stem)}.cpp").write_text(
            r.get("code", ""), encoding="utf-8")

    # <stem>_registrations.cpp ：源文件原文 + 注册注释块
    reg_rows: List[Dict] = []
    for r in class_recs + func_recs:
        for reg in r.get("registrations", []):
            reg_rows.append({
                "record_name": r.get("name", "?"), "qualified_name": r.get("qualified_name", ""),
                "namespace": r.get("namespace", ""), "line": reg.get("line", 0),
                "kind": reg.get("kind", ""), "call": reg.get("call", ""),
                "registration_class": reg.get("registration_class", ""),
            })
    if reg_rows:
        src = _resolve_source_cpp((class_recs + func_recs)[0].get("file_path", ""))
        original = src.read_text(encoding="utf-8", errors="replace") if src else ""
        (module_dir / f"{cpp_stem}_registrations.cpp").write_text(
            original + _render_appendix(reg_rows, cpp_stem), encoding="utf-8")


def _already_done(out_root: Path, category: str, cpp_stem: str) -> bool:
    d = out_root / category / cpp_stem
    return (d / "child_class.json").exists() or (d / "function_tests.json").exists()


def _select_vk_cpps(modules_root: Path, limit: int, sources: List[str]) -> List[Path]:
    """Resolve a bounded, reproducible Vulkan source selection."""
    if not sources:
        cpps = sorted(modules_root.rglob("*.cpp"))
        return cpps[:limit] if limit > 0 else cpps

    root = modules_root.resolve()
    selected: List[Path] = []
    seen = set()
    for raw in sources:
        requested = Path(raw.replace("\\", "/"))
        candidate = requested if requested.is_absolute() else root / requested
        try:
            resolved = candidate.resolve(strict=True)
        except FileNotFoundError as exc:
            raise ValueError(f"Vulkan source does not exist: {raw}") from exc
        try:
            resolved.relative_to(root)
        except ValueError as exc:
            raise ValueError(f"Vulkan source is outside the module root: {raw}") from exc
        if not resolved.is_file() or resolved.suffix.lower() != ".cpp":
            raise ValueError(f"Vulkan source must be a .cpp file: {raw}")
        key = str(resolved).casefold()
        if key not in seen:
            seen.add(key)
            selected.append(resolved)
    return selected


def run_vk(limit: int, resume: bool, batch: int, sources: List[str]) -> Dict[str, int]:
    """VK 侧：process_vk_cpp 已自带 4 字段注入，分批重建 ASTUtils 释放句柄。"""
    from vk_extract import process_vk_cpp, VK_MODULES_ROOT
    out_root = config.VK_OUTPUT_ROOT
    cpps = _select_vk_cpps(VK_MODULES_ROOT, limit, sources)
    todo = [c for c in cpps
            if not (resume and _already_done(out_root, _category_of(c, VK_MODULES_ROOT, out_root), c.stem))]
    logger.info("VK: %d cpp (%d after resume filter)", len(cpps), len(todo))

    stat = {"cpp": 0, "class": 0, "func": 0, "err": 0}
    for start in range(0, len(todo), batch):
        au = ASTUtils(project_root=config.SOURCE_ROOT, build_root=config.BUILD_ROOT,
                      preferred_configurations=config.PREFERRED_CONFIGURATIONS)
        for cpp in todo[start:start + batch]:
            category = _category_of(cpp, VK_MODULES_ROOT, out_root)
            try:
                res = process_vk_cpp(cpp, au)
                recs = res["class_records"] + res["function_records"]
                if recs:
                    _write_module(recs, category, cpp.stem, out_root)
                stat["cpp"] += 1
                stat["class"] += len(res["class_records"])
                stat["func"] += len(res["function_records"])
            except Exception as e:
                stat["err"] += 1
                logger.error("VK FAIL %s: %s", cpp.name, e)
        au.clear_runtime_caches(keep_compile_args=True)
        gc.collect()
    return stat


def main() -> int:
    ap = argparse.ArgumentParser(description="Extract Vulkan CTS test cases for RQ2")
    selection = ap.add_mutually_exclusive_group()
    selection.add_argument("--limit", type=int, default=0, help="只跑前 N 个 Vulkan cpp（调试）")
    selection.add_argument(
        "--source",
        action="append",
        default=[],
        metavar="RELATIVE_CPP",
        help="只跑相对 modules/vulkan 的指定 cpp；可重复传入",
    )
    ap.add_argument("--resume", action="store_true", help="跳过已产出的模块")
    ap.add_argument("--batch", type=int, default=80, help="VK：每批重建 ASTUtils 的 cpp 数")
    args = ap.parse_args()

    try:
        config.ensure_vk_prerequisites()
    except RuntimeError as exc:
        ap.error(str(exc))
    config.ensure_output_dirs()
    logger.info("配置:\n%s", config.describe())
    t0 = time.time()

    try:
        result = run_vk(args.limit, args.resume, args.batch, args.source)
    except ValueError as exc:
        ap.error(str(exc))
    logger.info("VK 结果: %s", result)

    logger.info("完成，用时 %.1fs → %s", time.time() - t0, config.OUTPUT_ROOT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
