"""extract.py — 从 VK-GL-CTS 源码树提取 Vulkan 测试用例数据集。

这是 RQ2 候选池构建的入口。Vulkan 提取核心为 vk_extract.process_vk_cpp
（单遍 AST + 继承链 DFS，自带 4 字段注入），统一注入
（registration_class / mount_code_id / mount_codes / cross_registrations），
并就地注入结构编号（class_id / class_type / trace），
再按 <category>/<cpp_stem>/ 落盘：child_class.json / function_tests.json / case_sources/ / <stem>_registrations.cpp。

用法：
  python extract.py                         # Vulkan 全量
  python extract.py --limit 5                # 只跑前 5 个 Vulkan cpp（调试）
  python extract.py --source draw/vktDrawMultipleInterpolationTests.cpp
  python extract.py --resume                 # 跳过已产出的模块
  python config.py                            # 先确认路径配置是否正确
"""
